/// Finds the most specific opening name for a SAN move list, or null.
String? openingName(List<String> sans) {
  for (var len = sans.length; len >= 1; len--) {
    final key = sans.take(len).join(' ');
    final name = _openings[key];
    if (name != null) return name;
  }
  return null;
}

/// Whether the full sequence so far is a known book line.
bool isBookLine(List<String> sans) => _openings.containsKey(sans.join(' '));
