"""Renders the app icon: the in-app faceted knight on an M3 primary field.

Writes
  assets/icon/icon.png                      full-bleed icon for
                                            flutter_launcher_icons (iOS, web,
                                            desktop, legacy Android mipmaps)
  android/.../mipmap-anydpi-v26/ic_launcher.xml + drawable/*.xml
                                            adaptive icon as vector drawables:
                                            background follows the system's
                                            dynamic color (Material You) on
                                            Android 12+, and a monochrome layer
                                            enables Android 13 themed icons.

Usage (from the repo root):
  python tool/make_icon.py && dart run flutter_launcher_icons
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / 'android/app/src/main/res'

# Static fallback = seed #6750A4 primary (tone 40) and a darker facet.
PRIMARY, PRIMARY_SHADE = '#6750A4', '#5D4699'
# Android 12+: the launcher resolves these against the wallpaper palette.
DYNAMIC, DYNAMIC_SHADE = '@android:color/system_accent1_600', '@android:color/system_accent1_700'


def hexc(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


# Same tones as the ivory set in lib/ui/widgets/board_theme.dart.
LEFT = (hexc('#E9D6BA'), hexc('#F2E3CD'), hexc('#DDC3A0'))
RIGHT = (hexc('#D0B388'), hexc('#DCC29C'), hexc('#C6A87D'))


def tone(side, tilt):
    base, up, down = side
    return lerp(base, up, tilt) if tilt >= 0 else lerp(base, down, -tilt)


def knight_facets():
    """(points, rgb, lit) in the 100-unit piece box, as in board_theme.dart."""
    ear, ridge, throat = (54.5, 29), (57, 49), (53, 51.5)
    snout_top, snout_bottom, chin = (30.6, 51.5), (30.6, 60.5), (35, 62)
    neck_front, neck_mid = (36, 82.5), (58, 82.5)
    back_top, back_bottom, neck_back = (70, 46), (70, 77), (64, 82.5)
    facets = [
        ([ear, ridge, snout_top], tone(LEFT, 0.8), True),
        ([snout_top, ridge, throat, chin, snout_bottom], tone(LEFT, -0.2), True),
        ([throat, ridge, neck_mid, neck_front], tone(LEFT, 0.5), True),
        ([ear, back_top, ridge], tone(RIGHT, 0.7), False),
        ([ridge, back_top, back_bottom, neck_back, neck_mid], tone(RIGHT, 0), False),
    ]
    stand = [(82.5, 13.6), (84, 13.6), (89.5, 19.7), (96, 19.7)]
    for (y0, w0), (y1, w1) in zip(stand, stand[1:]):
        t = max(-1, min(1, (w1 - w0) / (y1 - y0) * 1.2))
        facets.append(([(50 - w0, y0), (50, y0), (50, y1), (50 - w1, y1)], tone(LEFT, t), True))
        facets.append(([(50 + w0, y0), (50, y0), (50, y1), (50 + w1, y1)], tone(RIGHT, t), False))
    return facets


FACETS = knight_facets()


def placed(size, height_frac):
    """Facets scaled and centred in a size×size canvas."""
    xs = [x for pts, _, _ in FACETS for x, _ in pts]
    ys = [y for pts, _, _ in FACETS for _, y in pts]
    k = size * height_frac / (max(ys) - min(ys))
    ox = size / 2 - (min(xs) + max(xs)) / 2 * k
    oy = size / 2 - (min(ys) + max(ys)) / 2 * k
    return [([(ox + x * k, oy + y * k) for x, y in pts], c, lit) for pts, c, lit in FACETS]


def write_png(path):
    ss, n = 4, 1024 * 4
    img = Image.new('RGB', (n, n), hexc(PRIMARY))
    d = ImageDraw.Draw(img)
    d.polygon([(n, 0), (n, n), (0, n)], fill=hexc(PRIMARY_SHADE))
    for pts, c, _ in placed(n, 0.62):
        d.polygon(pts, fill=c)
        d.line(pts + [pts[0]], fill=c, width=ss * 2, joint='curve')
    path.parent.mkdir(parents=True, exist_ok=True)
    img.resize((1024, 1024), Image.LANCZOS).save(path, optimize=True)


def path_data(pts):
    return 'M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in pts) + ' Z'


def vector(paths):
    body = '\n'.join(paths)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icon.py; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''


def facet_path(pts, fill, alpha=None):
    a = '' if alpha is None else f'\n        android:fillAlpha="{alpha}"\n        android:strokeAlpha="{alpha}"'
    # Hairline stroke in the same colour hides seams between facets.
    return f'''    <path
        android:pathData="{path_data(pts)}"
        android:fillColor="{fill}"
        android:strokeColor="{fill}"
        android:strokeWidth="0.15"{a} />'''


def colors(bg, shade):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icon.py; do not edit by hand. -->
<resources>
    <color name="ic_launcher_background">{bg}</color>
    <color name="ic_launcher_background_shade">{shade}</color>
</resources>
'''


def write_android():
    # Adaptive icons keep content inside the central 66dp safe zone.
    knight = placed(108, 0.46)
    files = {
        'mipmap-anydpi-v26/ic_launcher.xml': '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icon.py; do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''',
        'drawable/ic_launcher_background.xml': vector([
            facet_path([(0, 0), (108, 0), (108, 108), (0, 108)], '@color/ic_launcher_background'),
            facet_path([(108, 0), (108, 108), (0, 108)], '@color/ic_launcher_background_shade'),
        ]),
        'drawable/ic_launcher_foreground.xml': vector(
            [facet_path(pts, '#FF%02X%02X%02X' % c) for pts, c, _ in knight]),
        # Themed icons tint by alpha, so the shaded half stays visible.
        'drawable/ic_launcher_monochrome.xml': vector(
            [facet_path(pts, '#FFFFFFFF', None if lit else 0.7) for pts, _, lit in knight]),
        'values/ic_launcher_colors.xml': colors(PRIMARY, PRIMARY_SHADE),
        'values-v31/ic_launcher_colors.xml': colors(DYNAMIC, DYNAMIC_SHADE),
    }
    for rel, text in files.items():
        p = RES / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    write_png(ROOT / 'assets/icon/icon.png')
    write_android()
